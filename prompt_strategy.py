# Main interaction flow
def run_interactive_story():
    show_initial_prompt()
    choice = ask_user_choice()
    scene_description, text_input = handle_choice(choice)
    character_description, goal_description = extract_character_and_goal(text_input)

    # START story
    initial_prompt = assemble_prompt(scene_description, character_description, goal_description)
    send_to_story_generator(initial_prompt)

    story_so_far = f"{character_description} enters the scene. {scene_description}"

    # CONTINUE loop
    while True:
        cont = input("\nWould you like to continue the story? (y/n): ").strip().lower()
        if cont == "y":
            story_so_far = continue_story(scene_description, character_description, story_so_far)
        elif cont == "n":
            print("\nThank you for playing! The story ends here.")
            break
        else:
            print("Please type 'y' or 'n'.")

    # Optional summary of actions
    print("\n Session Summary: Your Character's Decisions")
    for i, action in enumerate(user_actions, 1):
        print(f"{i}. {action}")

# --- Execute ---
if __name__ == "__main__":
    run_interactive_story()